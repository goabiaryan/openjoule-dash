export function getBlock(id) {
  return blocks.find((b) => b.id === id) || null;
}

export function blocksForLayer(layer) {
  return blocks.filter((b) => b.layer === layer && !b.spec?.optional);
}

export function gpuBlocksByGroup() {
  const gpus = blocksForLayer("gpu");
  const groups = [];
  for (const key of GPU_GROUP_ORDER) {
    const items = gpus.filter((b) => b.spec.gpuGroup === key);
    if (items.length) groups.push({ key, label: GPU_GROUP_LABELS[key] ?? key, blocks: items });
  }
  const grouped = new Set(groups.flatMap((g) => g.blocks.map((b) => b.id)));
  const other = gpus.filter((b) => !grouped.has(b.id));
  if (other.length) groups.push({ key: "other", label: "Other", blocks: other });
  return groups;
}

export function optionalBlocksForLayer(layer) {
  return blocks.filter((b) => b.layer === layer && b.spec?.optional);
}
